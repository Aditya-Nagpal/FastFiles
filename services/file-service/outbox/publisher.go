package outbox

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"log"
	"time"

	"github.com/Aditya-Nagpal/Cloud-File-Storage-System/services/file-service/db"
	"github.com/Aditya-Nagpal/Cloud-File-Storage-System/services/shared/events"
	"github.com/jackc/pgx/v5"
	"github.com/segmentio/kafka-go"
)

func Run(ctx context.Context, brokers []string, topic string) {
	writer := &kafka.Writer{
		Addr:         kafka.TCP(brokers...),
		Topic:        topic,
		Balancer:     &kafka.Hash{},
		RequiredAcks: kafka.RequireAll,
		Async:        false,
	}
	defer writer.Close()

	log.Println("Outbox publisher started")

	for {
		if ctx.Err() != nil {
			return
		}

		event, err := db.ClaimNextEvent(ctx)
		if errors.Is(err, pgx.ErrNoRows) {
			if !wait(ctx, time.Second) {
				return
			}
			continue
		}

		if err != nil {
			log.Printf("Outbox: failed to claim event: %v", err)
			if !wait(ctx, 2*time.Second) {
				return
			}
			continue
		}

		var payload events.EntryEvent
		if err := json.Unmarshal(event.Payload, &payload); err != nil {
			log.Printf("Outbox: invalid payload for event %d: %v", event.ID, err)
			db.RecordFailure(ctx, event.ID, err)
			continue
		}

		// Use the authoritative ID generated by PostgreSQL.
		payload.EventID = event.EventID

		messagePayload, err := json.Marshal(payload)
		if err != nil {
			log.Printf("Outbox: failed to encode event %d: %v", event.ID, err)
			db.RecordFailure(ctx, event.ID, err)
			continue
		}

		message := kafka.Message{
			Key:   fmt.Appendf(nil, "%d", payload.UserID),
			Value: messagePayload,
			Headers: []kafka.Header{
				{Key: "event_id", Value: []byte(event.EventID)},
				{Key: "event_type", Value: []byte(payload.EventType)},
			},
		}

		publishCtx, cancel := context.WithTimeout(ctx, 10*time.Second)
		err = writer.WriteMessages(publishCtx, message)
		cancel()

		if err != nil {
			log.Printf("Outbox: Kafka publish failed for event %d: %v", event.ID, err)
			db.RecordFailure(ctx, event.ID, err)
			continue
		}

		err = db.MarkEventAsPublished(ctx, event.ID)
		if err != nil {
			log.Printf(
				"Outbox: published event %d, but failed to mark it published: %v",
				event.ID, err,
			)
			// It may be published again after its claim expires.
			// Consumers must be idempotent.
			continue
		}

		log.Printf(
			"Outbox: published event_id=%s type=%s",
			event.EventID, payload.EventType,
		)
	}
}

func wait(ctx context.Context, duration time.Duration) bool {
	timer := time.NewTimer(duration)
	defer timer.Stop()

	select {
	case <-ctx.Done():
		return false
	case <-timer.C:
		return true
	}
}
